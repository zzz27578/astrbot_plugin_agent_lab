import fs from 'node:fs';
import assert from 'node:assert/strict';
import {capabilityGroups,renderCapabilityGraph,toggleCapability,toolEnabled} from '../../pages/agent-lab/scheme-settings.js';
const state={plugins:[{name:'example',display_name:'Example',activated:true},{name:'host-off',activated:false},{name:'astrbot_plugin_agent_lab',activated:true}],tools:[{name:'example_read',plugin_name:'example',active:true},{name:'example_write',plugin_name:'example',active:true},{name:'astrbot_file_read_tool',active:true},{name:'host_tool',plugin_name:'host-off',active:true}]};
let agent={name:'方案',plugin_overrides:{example:true},enabled_tools:[],isolation_policy:{mode:'strict',tool_mode:'full'}};
const group=id=>capabilityGroups(agent,state).find(g=>g.id===id);
assert.equal(toolEnabled(agent,state.tools[0],group('example')),true);
toggleCapability(agent,state,'tool','example_read',false);
agent=JSON.parse(JSON.stringify(agent));
assert.equal(toolEnabled(agent,state.tools[0],group('example')),false);
assert.equal(toolEnabled(agent,state.tools[1],group('example')),true);
toggleCapability(agent,state,'group','example',false);
assert.equal(toolEnabled(agent,state.tools[1],group('example')),false);
toggleCapability(agent,state,'group','example',true);
assert.equal(toolEnabled(agent,state.tools[0],group('example')),true);
toggleCapability(agent,state,'all','',false);
assert.equal(agent.isolation_policy.tool_mode,'no_external');
assert.equal(toolEnabled(agent,state.tools[2],group('__core__')),false);
toggleCapability(agent,state,'tool','example_read',true);
assert.equal(toolEnabled(agent,state.tools[0],group('example')),true);
assert.equal(toolEnabled(agent,state.tools[1],group('example')),false);
toggleCapability(agent,state,'all','',true);
assert.equal(toolEnabled(agent,state.tools[2],group('__core__')),true);
assert.equal(toolEnabled(agent,state.tools[3],group('host-off')),false);
const html=renderCapabilityGraph(agent,state,s=>String(s||''),new Set(['example']));
assert.ok(html.includes('scheme-capability-node'));
assert.ok(html.includes('data-capability-group="example" open'));
assert.ok(html.includes('全部禁用'));
assert.ok(!html.includes('data-global-skill'));
const source=fs.readFileSync(new URL('../../pages/agent-lab/app.js',import.meta.url),'utf8');
assert.ok(!source.includes('workflowGlobalOpen'));
assert.ok(source.includes('if (route === "preset-settings") renderPresetRulesPage();'));
const navigation=fs.readFileSync(new URL('../../pages/agent-lab/navigation.js',import.meta.url),'utf8');
assert.ok(navigation.includes('data-nav-action="preset-rules"'));
console.log('Scheme UI smoke passed: graph groups, nested tool switches, bulk toggles, save round-trip, host-off protection and direct preset entry.');
