import type { Node, Edge } from "@xyflow/react";
export type Kind = "agent" | "tool" | "approval";
export type NodeData = {
  kind: Kind;
  title: string;
  instruction: string;
  tool_name?: string;
  arguments?: Record<string, unknown>;
  status?: string;
  summary?: string;
  [key: string]: unknown;
};
export type FlowNode = Node<NodeData>;
export type Graph = { nodes: FlowNode[]; edges: Edge[] };
export type Step = {
  id: string;
  title: string;
  instruction: string;
  status?: string;
  summary?: string;
  evidence?: unknown;
  kind?: Kind;
  tool_name?: string;
  arguments?: Record<string, unknown>;
  depends_on?: string[];
};
export type Task = {
  task_id: string;
  title: string;
  goal: string;
  status: string;
  steps: Step[];
  graph?: Graph;
  plan_version: number;
  approved_version?: number;
  current_step_id?: string;
  summary?: string;
  next_action?: string;
  constraints?: string[] | string;
  acceptance?: string[] | string;
  execution_mode: "sandbox" | "direct";
  workspace?: string;
  source_umo?: string;
  provider_id?: string;
  owner_id?: string;
  created_at?: string;
  updated_at?: string;
  revision?: number;
  approvals?: Array<Record<string, unknown>>;
  inbox?: Array<Record<string, unknown>>;
  events?: Array<Record<string, unknown>>;
  tool_calls?: Array<Record<string, unknown>>;
  memories?: Array<Record<string, unknown>>;
  project_memories?: Array<Record<string, unknown>>;
  project_key?: string;
  scheduled_at?: string;
  schedule_armed?: boolean;
  schedule_plan_version?: number;
  followups?: Array<Record<string, unknown>>;
  [key: string]: unknown;
};
export type Template = {
  template_id: string;
  name: string;
  description: string;
  graph: Graph;
  revision?: number;
};
export type State = {
  tasks: Task[];
  templates: Template[];
  providers: { provider_id: string; model?: string }[];
  tools: {
    name: string;
    description?: string;
    enabled?: boolean;
    allowed?: boolean;
  }[];
  config: Record<string, unknown>;
  legacy_tasks?: Array<Record<string, unknown>>;
};
